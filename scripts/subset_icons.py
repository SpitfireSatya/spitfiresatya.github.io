#!/usr/bin/env python3
"""Cut Font Awesome down to the icons the site actually uses.

Usage:  bundle exec jekyll build && python3 scripts/subset_icons.py
  Scans the built site (_site/, or the directory given as the first argument)
  plus the templates and scripts that inject icons at runtime, then writes:
    _sass/_fa-icons-used.scss                 the icon classes to generate
    assets/webfonts/fa-solid-900-subset.woff  solid glyphs actually used
    assets/webfonts/fa-brands-400-subset.woff brand glyphs actually used
  assets/css/fontawesome.scss builds against these instead of the full set
  (about 2,000 icons, 346 KB). Re-run it after adding an icon anywhere.
Needs fontTools (pyftsubset). Writes WOFF rather than WOFF2 so it needs no
Brotli extension; for a few dozen glyphs the difference is a few KB.
"""
import os
import re
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FA = os.path.join(REPO, "_sass", "vendor", "font-awesome")
FONTS = os.path.join(REPO, "assets", "webfonts")
# icons added by JavaScript or swapped at runtime never appear in built HTML
SOURCES = ["_includes", "_layouts", "assets/js/_main.js", "_config.yml", "_data"]
ALWAYS = {"sun", "moon"}          # the theme script swaps these classes


def parse_maps():
    text = open(os.path.join(FA, "_variables.scss")).read()
    code = dict(re.findall(r"^\$fa-var-([a-z0-9-]+):\s*\\([0-9a-f]+);", text, re.M))

    def block(name):
        body = re.search(r"^\$" + name + r": \((.*?)^\);", text, re.M | re.S).group(1)
        return dict(re.findall(r'"([a-z0-9-]+)": \$fa-var-([a-z0-9-]+)', body))
    return code, block("fa-icons"), block("fa-brand-icons")


def used_names(site):
    names = set(ALWAYS)
    pat = re.compile(r"\bfa-([a-z0-9-]+)")
    roots = [site] + [os.path.join(REPO, s) for s in SOURCES]
    for root in roots:
        paths = [root] if os.path.isfile(root) else [
            os.path.join(d, f) for d, _, fs in os.walk(root) for f in fs]
        for p in paths:
            if p.endswith((".html", ".js", ".yml", ".yaml", ".md", ".json")):
                with open(p, errors="ignore") as fh:
                    names.update(pat.findall(fh.read()))
    return names


def subset(src, dst, codes):
    unicodes = ",".join(f"U+{c}" for c in sorted(codes))
    subprocess.run(["pyftsubset", src, f"--unicodes={unicodes}", "--flavor=woff",
                    f"--output-file={dst}", "--layout-features=", "--no-hinting",
                    "--desubroutinize"], check=True)


def main():
    site = sys.argv[1] if len(sys.argv) > 1 else os.path.join(REPO, "_site")
    if not os.path.isdir(site):
        sys.exit(f"no built site at {site}; run `bundle exec jekyll build` first")
    code, solid, brands = parse_maps()
    names = used_names(site)
    s_used = {n: v for n, v in solid.items() if n in names}
    b_used = {n: v for n, v in brands.items() if n in names}

    lines = ["// Generated by scripts/subset_icons.py; do not edit by hand.",
             "// The icons the site uses; fontawesome.scss builds only these.",
             "$fa-icons: ("] + [f'  "{n}": $fa-var-{v},' for n, v in sorted(s_used.items())] + [
             ");", "$fa-brand-icons: ("] + [
             f'  "{n}": $fa-var-{v},' for n, v in sorted(b_used.items())] + [");", ""]
    open(os.path.join(REPO, "_sass", "_fa-icons-used.scss"), "w").write("\n".join(lines))

    subset(os.path.join(FONTS, "fa-solid-900.ttf"), os.path.join(FONTS, "fa-solid-900-subset.woff"),
           {code[v] for v in s_used.values()})
    subset(os.path.join(FONTS, "fa-brands-400.ttf"), os.path.join(FONTS, "fa-brands-400-subset.woff"),
           {code[v] for v in b_used.values()})
    for f in ("fa-solid-900-subset.woff", "fa-brands-400-subset.woff"):
        print(f"{f}: {os.path.getsize(os.path.join(FONTS, f)) / 1024:.1f} KB")
    print("solid:", ", ".join(sorted(s_used)))
    print("brands:", ", ".join(sorted(b_used)))


if __name__ == "__main__":
    main()
